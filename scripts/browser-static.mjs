/** Run after build + browser-packages, with the static server on TEST_URL (default :3001). */
import { chromium, expect } from "@playwright/test";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve, dirname, sep } from "node:path";
import { unzipSync } from "fflate";
const results = JSON.parse(await readFile(".artifacts/browser-packages-results.json", "utf8"));
if(!results.passed) throw new Error("Run the passing browser-packages check first.");
const root=resolve("out");
const files=unzipSync(new Uint8Array(await readFile(results.packagePath)));
const manifest=JSON.parse(new TextDecoder().decode(files[`projects/${results.projectId}/project.json`]));
for(const [name,bytes] of Object.entries(files)) {
  if(!name.startsWith(`projects/${results.projectId}/`)) continue;
  const path=resolve(root,name);
  if(!path.startsWith(root+sep)||name.split("/").includes("..")) throw new Error("Unsafe fixture package path.");
  await mkdir(dirname(path),{recursive:true});await writeFile(path,bytes);
}
const base=process.env.TEST_URL||"http://localhost:3001";
const browser=await chromium.launch({headless:true});
const checks=[];
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto(`${base}/experience/?project=${results.projectId}`,{waitUntil:"domcontentloaded"});
  await expect(page.locator(".experience-info>h1")).toHaveText(manifest.name);
  await expect(page.locator("canvas")).toHaveCount(1);
  await expect(page.locator(".viewer-status")).toHaveCount(0,{timeout:30000});
  await expect(page.getByRole("button",{name:"Explore Main entrance",exact:true})).toBeVisible();
  checks.push("Uploaded project static package loads actual model in a fresh browser context without editor IndexedDB");
  const storage=await page.evaluate(()=>indexedDB.databases());
  if(storage.some(db=>db.name==="atlasar-studio")) throw new Error("Static visitor unexpectedly required editor storage.");
  checks.push("Static visitor does not create or require editor database");
  await page.screenshot({path:".artifacts/static-experience.png",fullPage:true});
  await page.goto(base,{waitUntil:"domcontentloaded"});
  await expect(page.locator(".project-card")).toHaveCount(3);
  await page.getByRole("button",{name:"Share The Courtyard",exact:true}).click();
  const link=await page.getByRole("textbox",{name:"Experience URL"}).inputValue();
  if(!link.includes("#p="))throw new Error("Expected self-contained project manifest.");
  const [download]=await Promise.all([page.waitForEvent("download"),page.getByRole("button",{name:"Download QR SVG"}).click()]);
  await download.saveAs(".artifacts/sample-qr.svg");
  const svg=await readFile(".artifacts/sample-qr.svg","utf8");
  if(!svg.includes("<svg")||!svg.includes("<path"))throw new Error("QR download is not a valid SVG drawing.");
  checks.push("QR SVG download generated for exact displayed manifest URL");
  const fresh=await browser.newContext();const visitor=await fresh.newPage();
  visitor.on("pageerror",e=>errors.push(e.message));
  await visitor.goto(link,{waitUntil:"domcontentloaded"});
  await expect(visitor.locator(".experience-info>h1")).toHaveText("The Courtyard");
  await expect(visitor.locator(".viewer-status")).toHaveCount(0,{timeout:30000});
  await expect(visitor.locator("canvas")).toHaveCount(1);
  checks.push("Portable manifest link works in an independent fresh browser profile");
  await visitor.goto(`${base}/experience/#p=invalid`,{waitUntil:"domcontentloaded"});
  await expect(visitor.locator(".center-page [role=alert]")).toContainText("could not be loaded");
  checks.push("Malformed shared project link has useful error feedback");
  await mkdir(resolve(root,"projects/qa-missing"),{recursive:true});
  await writeFile(resolve(root,"projects/qa-missing/project.json"),JSON.stringify({...manifest,id:"qa-missing",model:{url:"/assets/missing-test-model.glb",name:"Missing test model"}}));
  await visitor.goto(`${base}/experience/?project=qa-missing`,{waitUntil:"domcontentloaded"});
  await expect(visitor.locator(".viewer-error")).toContainText("Unable to load this 3D model",{timeout:20000});
  await expect(visitor.getByRole("button",{name:"Try loading again"})).toBeVisible();
  await Promise.all([visitor.waitForResponse(response=>response.url().endsWith("/assets/missing-test-model.glb")),visitor.getByRole("button",{name:"Try loading again"}).click()]);
  await expect(visitor.locator(".viewer-error")).toContainText("Unable to load this 3D model");
  checks.push("Missing model produces useful feedback and a working retry control");
  await mkdir(resolve(root,"projects/qa-invalid"),{recursive:true});
  await writeFile(resolve(root,"projects/qa-invalid/project.json"),JSON.stringify({...manifest,id:"qa-invalid",schemaVersion:999}));
  await visitor.goto(`${base}/experience/?project=qa-invalid`,{waitUntil:"domcontentloaded"});
  await expect(visitor.locator(".center-page [role=alert]")).toContainText("only project format version 1");
  checks.push("Unsupported published manifest schema is rejected before model loading");
  if(errors.length)throw new Error(errors.join("; "));
  await writeFile(".artifacts/browser-static-results.json",JSON.stringify({checks,errors,passed:true},null,2));
  for(const check of checks)console.log(`PASS ${check}`);
} finally {await browser.close();}
